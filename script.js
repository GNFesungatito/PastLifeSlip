let current = 0;
const scores = {权:0, 情:0, 智:0, 逸:0, 韧:0};

function checkGate() {
  const val = document.getElementById('gateInput').value.trim().toUpperCase();
  if (val === ACCESS_CODE) {
    document.getElementById('gate').classList.add('hidden');
    document.getElementById('quiz').classList.remove('hidden');
    renderQuestion();
  } else {
    document.getElementById('gateMsg').textContent = '口令不对，请检查后重试';
  }
}

function renderQuestion() {
  const quizEl = document.getElementById('quiz');
  const q = questions[current];
  const progress = Math.round((current / questions.length) * 100);
  quizEl.innerHTML = `
    <div class="progress"><div style="width:${progress}%"></div></div>
    <p style="color:#6b6280;font-size:12px;margin:0 0 14px;letter-spacing:1px;">第 ${current+1} / ${questions.length} 题</p>
    <h2>${q.q}</h2>
    ${q.o.map(o=>`<button class="option" onclick="answer('${o[1]}')">${o[0]}</button>`).join('')}
  `;
  window.scrollTo(0,0);
}

function answer(k) {
  scores[k]++;
  current++;
  if (current < questions.length) renderQuestion();
  else showResult();
}

/* 余弦相似度匹配最接近的身份 */
function getResult(scores) {
  const dims = ['权','情','智','逸','韧'];
  const total = dims.reduce((s,d)=>s+scores[d],0) || 1;
  const userVec = dims.map(d => scores[d]/total);

  let best = null, bestSim = -1;
  for (const [name, profile] of Object.entries(identityProfiles)) {
    const pVec = dims.map(d => profile[d]);
    const dot = userVec.reduce((s,v,i)=>s+v*pVec[i],0);
    const uMag = Math.sqrt(userVec.reduce((s,v)=>s+v*v,0));
    const pMag = Math.sqrt(pVec.reduce((s,v)=>s+v*v,0));
    const sim = dot / (uMag * pMag);
    if (sim > bestSim) { bestSim = sim; best = name; }
  }
  return best;
}

function showResult() {
  const name = getResult(scores);
  const content = identityContent[name];
  document.getElementById('quiz').classList.add('hidden');
  const r = document.getElementById('result');
  r.classList.remove('hidden');

  r.innerHTML = `
    <p class="result-label">你的上一世身份</p>
    <div class="result-emoji">${content.emoji}</div>
    <div class="result-title">${name}</div>
    <p class="result-tagline">${content.tagline}</p>
    <div class="result-divider"></div>
    <div class="result-desc">${content.story}</div>
    <div class="result-reminder">${content.reminder}</div>
    <p class="result-code">访问口令：${ACCESS_CODE}</p>
    <p class="tip" style="margin-top:12px;">仅供娱乐参考，不构成专业诊断。</p>
  `;
  window.scrollTo(0,0);
}